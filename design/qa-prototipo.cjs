  await page.locator('#app [data-action="preview-selection"]').click();
  await page.screenshot({path:path.join(__dirname,'preview','03-fragmento.png'),fullPage:true});
  await page.locator('#app [data-action="save-clip"]').click();
  assert.match(await page.locator('.clip-summary').innerText(),/00:42 — 01:08/);
  await page.locator('#app [data-action="back"]').click();
  await page.waitForFunction(()=>document.querySelector('#app h1')?.textContent==='Proyectos');
  const projectId=await page.evaluate(()=>JSON.parse(localStorage.getItem('amv-manager-design-v1'))[0].id);
